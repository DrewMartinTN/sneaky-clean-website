function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function jsonForHtml(value) {
  return JSON.stringify(value, null, 2).replaceAll("<", "\\u003c");
}

function prefixedAsset(src) {
  if (/^https?:\/\//.test(src)) return src;
  return `../${src.replace(/^\/+/, "")}`;
}

function absoluteAsset(src) {
  if (/^https?:\/\//.test(src)) return src;
  return `${BASE_URL}/${src.replace(/^\/+/, "")}`;
}

function imageDimensions(src) {
  const normalized = src.replace(/^\/+/, "");
  const dimensions = IMAGE_DIMENSIONS[normalized];
  if (!dimensions) {
    throw new Error(`Missing dimensions for image: ${src}`);
  }
  return `width="${dimensions[0]}" height="${dimensions[1]}"`;
}

// AVIF variants generated by images:responsive; keyed by original path.
function avifSrcset(normalized) {
  const workImage = normalized.match(/^(assets\/images\/work\/case-\d+)\.webp$/);
  if (workImage) {
    return [640, 960, 1200]
      .map((w) => `${prefixedAsset(`${workImage[1]}-${w}.avif`)} ${w}w`)
      .join(", ");
  }
  if (normalized === "assets/images/sneaky-clean-mascot.png") {
    return [
      `${prefixedAsset("assets/images/sneaky-clean-mascot-96.avif")} 96w`,
      `${prefixedAsset("assets/images/sneaky-clean-mascot-320.avif")} 320w`,
    ].join(", ");
  }
  return null;
}

function responsiveImage(src, alt, options = {}) {
  const normalized = src.replace(/^\/+/, "");
  const sizes = options.sizes ? `sizes="${escapeHtml(options.sizes)}"` : "";
  const attributes = [
    options.className ? `class="${escapeHtml(options.className)}"` : "",
    `src="${escapeHtml(prefixedAsset(normalized))}"`,
    `alt="${escapeHtml(alt)}"`,
    imageDimensions(normalized),
    options.loading ? `loading="${options.loading}"` : "",
    "decoding=\"async\"",
    options.fetchPriority ? `fetchpriority="${options.fetchPriority}"` : "",
  ]
    .filter(Boolean)
    .join(" ");

  const srcset = avifSrcset(normalized);
  if (!srcset) return `<img ${attributes}>`;
  return `<picture><source type="image/avif" srcset="${srcset}" ${sizes}><img ${attributes}></picture>`;
}

function hrefForPage(href) {
  if (!href) return "#";
  if (/^(https?:|tel:|mailto:|#)/.test(href)) return href;
  return href;
}

